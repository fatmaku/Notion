export function pickLang(list) {
  for (const l of list || []) {
    const c = String(l || '').slice(0, 2).toLowerCase();
    if (TEXT[c]) return c;
  }
  return 'en';
}

export function t(lang, key) {
  const pack = TEXT[lang] || TEXT.en;
  return pack[key] != null ? pack[key] : TEXT.en[key] != null ? TEXT.en[key] : key;
}
